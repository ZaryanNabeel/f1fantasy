import random
import secrets
from pathlib import Path

import click
from flask import current_app

from . import db


def register_cli(app):
    @app.cli.command("create-admin")
    @click.option("--username", prompt=True)
    @click.option("--email", prompt=True)
    @click.option("--password", prompt=True, hide_input=True, confirmation_prompt=True)
    def create_admin(username, email, password):
        """Create an admin account (the only way to get one)."""
        from .auth.services import create_user, uniqueness_errors, validate_registration

        errors = validate_registration(username, email, password, password) or uniqueness_errors(username, email)
        if errors:
            raise click.ClickException(" ".join(errors.values()))
        create_user(username, email, password, role="admin")
        click.echo(f"Admin '{username}' created.")

    @app.cli.command("sync-data")
    @click.option("--season", type=int, default=None, help="Defaults to F1_SEASON.")
    @click.option("--use-cache", is_flag=True, help="Reuse JSON in data/cache/ instead of calling the API.")
    def sync_data(season, use_cache):
        """Import calendar, drivers, teams and results from Jolpica-F1."""
        from .f1data.jolpica import sync_season

        _, summary = sync_season(season or current_app.config["F1_SEASON"], use_cache=use_cache)
        click.echo(summary)

    @app.cli.command("export-seed")
    @click.option("--season", type=int, default=None)
    def export_seed(season):
        """Write sql/seed_<season>.sql with teams, drivers, races and race_results."""
        season = season or current_app.config["F1_SEASON"]
        conn = db.get_db()
        tables = [
            ("teams", "SELECT id, constructor_ref, name, nationality, colour_hex, price, active FROM teams ORDER BY id", ()),
            ("drivers", "SELECT id, driver_ref, code, permanent_number, first_name, last_name, nationality, "
                        "team_id, price, active FROM drivers ORDER BY id", ()),
            ("races", "SELECT id, season, round, name, circuit, country, race_date, has_sprint FROM races "
                      "WHERE season = %s ORDER BY id", (season,)),
            ("race_results", "SELECT rr.id, rr.race_id, rr.driver_id, rr.team_id, rr.session_type, rr.position, "
                             "rr.grid, rr.points, rr.status FROM race_results rr JOIN races r ON r.id = rr.race_id "
                             "WHERE r.season = %s ORDER BY rr.id", (season,)),
        ]
        out = [f"-- Seed snapshot for season {season}, generated by `flask export-seed`.",
               "-- Load after schema.sql into an empty database.", "USE f1fantasy;", ""]
        for table, sql, args in tables:
            rows = db.query(sql, args)
            if not rows:
                continue
            cols = list(rows[0].keys())
            out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
            out.append(",\n".join("  (" + ", ".join(conn.escape(r[c]) for c in cols) + ")" for r in rows) + ";")
            out.append("")
        path = Path(current_app.root_path).parent / "sql" / f"seed_{season}.sql"
        path.write_text("\n".join(out), encoding="utf-8", newline="\n")
        click.echo(f"Wrote {path}")

    @app.cli.command("seed-demo")
    def seed_demo():
        """Create 5 demo users with valid fantasy teams. Passwords are printed once."""
        from .auth.services import create_user
        from .fantasy.services import load_catalog, save_team, validate_picks

        season = current_app.config["F1_SEASON"]
        drivers, teams = load_catalog()
        driver_ids = [d for d, v in drivers.items() if v["active"]]
        team_ids = [t for t, v in teams.items() if v["active"]]
        if len(driver_ids) < 5 or not team_ids:
            raise click.ClickException("Load seed data first: need at least 5 active drivers and 1 team.")
        rng = random.Random()
        for name in ("alice", "bilal", "chen", "dana", "emeka"):
            username = f"demo_{name}"
            if db.query("SELECT 1 FROM users WHERE username = %s", (username,), one=True):
                click.echo(f"{username}: exists, skipped")
                continue
            team_name = f"{name.title()} Racing"
            for _ in range(5000):
                picks, constructor = rng.sample(driver_ids, 5), rng.choice(team_ids)
                if not validate_picks(team_name, picks, constructor, drivers, teams):
                    break
            else:
                raise click.ClickException("Could not find a valid random team; check prices.")
            password = secrets.token_urlsafe(9) + "7a"
            user_id = create_user(username, f"{username}@example.com", password)
            errors = save_team(user_id, season, team_name, picks, constructor)
            if errors:
                raise click.ClickException(f"{username}: {errors}")
            click.echo(f"{username}  password: {password}  team: {team_name}")
